  @override
  Widget build(BuildContext context) {
    final filteredIcons = _icons.entries
        .where((entry) => entry.key.toLowerCase().contains(_searchQuery.toLowerCase()))
        .toList();

    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        const Text(
          'Icons Collection',
          style: TextStyle(fontSize: 24, fontWeight: FontWeight.bold),
        ),
        const SizedBox(height: 8),
        const Text(
          'A curated collection of common Material Icons available in the framework. Click any icon to copy its name.',
          style: TextStyle(color: Colors.grey, fontSize: 14),
        ),
        const SizedBox(height: 24),
        PPSearch(
          value: _searchQuery,
          placeholder: 'Search icons...',
          onChanged: (val) {
            setState(() {
              _searchQuery = val;
            });
          },
        ),
        const SizedBox(height: 24),
        GridView.builder(
          shrinkWrap: true,
          physics: const NeverScrollableScrollPhysics(),
          gridDelegate: const SliverGridDelegateWithMaxCrossAxisExtent(
            maxCrossAxisExtent: 120,
            childAspectRatio: 1,
            crossAxisSpacing: 16,
            mainAxisSpacing: 16,
          ),
          itemCount: filteredIcons.length,
          itemBuilder: (context, index) {
            final entry = filteredIcons[index];
            return _buildIconTile(entry.key, entry.value);
          },
        ),
      ],
    );
  }

  Widget _buildIconTile(String name, IconData icon) {
    return Material(
      color: Colors.white,
      borderRadius: BorderRadius.circular(12),
      child: InkWell(
        onTap: () {
          Clipboard.setData(ClipboardData(text: 'Icons.$name'));
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(
              content: Text('Copied Icons.$name to clipboard'),
              duration: const Duration(seconds: 2),
            ),
          );
        },
        borderRadius: BorderRadius.circular(12),
        hoverColor: Colors.grey.shade100,
        child: Container(
          decoration: BoxDecoration(
            border: Border.all(color: Colors.grey.shade200),
            borderRadius: BorderRadius.circular(12),
          ),
          child: Column(
            mainAxisAlignment: MainAxisAlignment.center,
            children: [
              Icon(icon, size: 32, color: Colors.blueGrey.shade700),
              const SizedBox(height: 12),
              Padding(
                padding: const EdgeInsets.symmetric(horizontal: 4.0),
                child: Text(
                  name,
